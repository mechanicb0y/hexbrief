"""Record the demo fixture from a real (TLP:CLEAR) brief.json.

    python scripts/record_demo.py out/2026-11-15/brief.json [--others 40] [--no-llm]

Writes src/hexbrief/demo/findings.json (CLEAR findings only, top + N others) and,
unless --no-llm, a narrative generated by the local model over those findings,
**validated before it is saved** (src/hexbrief/demo/narrative.json). The demo then
runs without keys, MISP, OpenCTI or Ollama, and still passes the same gate.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from hexbrief.engine import finding_from_json, finding_json  # noqa: E402
from hexbrief.publish.public import is_clear  # noqa: E402

DEMO = REPO / "src" / "hexbrief" / "demo"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("brief_json", type=Path)
    ap.add_argument("--others", type=int, default=40)
    ap.add_argument("--no-llm", action="store_true")
    args = ap.parse_args()

    data = json.loads(args.brief_json.read_text(encoding="utf-8"))
    rows = [d for d in data["top"] + data["others"][: args.others] if is_clear(d["tlp"])]
    for d in rows:  # scores/reasons are recomputed at demo time
        d.pop("fid", None)
        d.pop("score", None)
        d.pop("reasons", None)
        d["iocs"] = d["iocs"][:40]
    DEMO.mkdir(exist_ok=True)
    meta = {"recorded_from": data["day"], "now": data["window"][1]}
    (DEMO / "findings.json").write_text(
        json.dumps({"meta": meta, "findings": rows}, indent=1, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"recorded {len(rows)} TLP:CLEAR findings")
    if args.no_llm:
        return 0

    from hexbrief.demo_mode import demo_run
    from hexbrief.llm.client import OllamaWriter

    with OllamaWriter("qwen3.5:4b") as w:
        result = demo_run(writer=w)
    if not result.llm_ok:
        print("model did not produce a faithful narrative; narrative not recorded")
        return 1
    (DEMO / "narrative.json").write_text(
        json.dumps(result.narrative, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print("recorded a validated narrative")
    _ = [finding_json(finding_from_json(r)) for r in rows]  # round-trip sanity check
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
