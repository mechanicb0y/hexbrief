<#
.SYNOPSIS
    Starts the lab MISP on https://127.0.0.1:8443 (on demand; stop it with misp-down.ps1).

.DESCRIPTION
    1. Clones the official MISP/misp-docker into docker/misp/upstream (git-ignored),
       pinned to $UpstreamCommit.
    2. Creates docker/misp/.env.misp from env.misp.template the first time, with every
       secret generated by gen-secrets.ps1 (values are never printed).
    3. Runs upstream compose + our override (127.0.0.1 only, no mail relay, lab sizing).
#>
[CmdletBinding()]
param([switch]$NoWait)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$UpstreamCommit = '2efbdcefd47cf6cd73889789d784044811b3edd8'  # misp-docker, 2026-11-11 (ADR-003)
$repo     = Split-Path -Parent $PSScriptRoot
$mispDir  = Join-Path $repo 'docker\misp'
$upstream = Join-Path $mispDir 'upstream'
$envFile  = Join-Path $mispDir '.env.misp'

# 1. upstream checkout at the pinned commit
if (-not (Test-Path (Join-Path $upstream '.git'))) {
    git clone --quiet https://github.com/MISP/misp-docker.git $upstream
    if ($LASTEXITCODE -ne 0) { throw 'git clone of MISP/misp-docker failed' }
}
$current = (git -C $upstream rev-parse HEAD).Trim()
if ($current -ne $UpstreamCommit) {
    git -C $upstream fetch --quiet origin
    git -C $upstream -c advice.detachedHead=false checkout --quiet $UpstreamCommit
    if ($LASTEXITCODE -ne 0) { throw "checkout of $UpstreamCommit failed" }
}

# 2. env file with generated secrets
if (-not (Test-Path $envFile)) {
    Copy-Item (Join-Path $mispDir 'env.misp.template') $envFile
    & (Join-Path $PSScriptRoot 'gen-secrets.ps1') -Path $envFile
}
if (Select-String -Path $envFile -Pattern '__replace_me__' -Quiet) {
    & (Join-Path $PSScriptRoot 'gen-secrets.ps1') -Path $envFile
}

# 3. TLS: nginx needs ssl/cert.pem + key.pem. Make a private lab CA + server cert once.
$sslDir = Join-Path $upstream 'ssl'
if (-not (Test-Path (Join-Path $sslDir 'cert.pem'))) {
    New-Item -ItemType Directory -Force $sslDir | Out-Null
    docker run --rm -v "${sslDir}:/out" -v "$(Join-Path $mispDir 'make-cert.sh'):/make-cert.sh:ro" `
        alpine:3.22 sh /make-cert.sh
    if ($LASTEXITCODE -ne 0) { throw 'lab certificate generation failed' }
}
Write-Host "MISP CA for clients: $(Join-Path $sslDir 'ca.pem')  (set MISP_VERIFY_SSL to this path)"

# 4. start
# Upstream healthchecks are tight (misp-modules ~11 s, misp-core ~75 s), but on
# Windows misp-core re-syncs its files into the bind mount on EVERY start, which
# takes several minutes. Compose then gives up with "dependency ... is unhealthy"
# even though the containers keep starting. `up -d` is idempotent, so keep
# re-running it until everything is up (max 20 min).
$deadline = (Get-Date).AddMinutes(20)
$try = 0
while ($true) {
    $try++
    docker compose -p hexbrief-misp --env-file $envFile `
        -f (Join-Path $upstream 'docker-compose.yml') -f (Join-Path $mispDir 'compose.override.yml') `
        up -d   # no 2>&1 here: PS 5.1 + ErrorAction Stop turns compose's stderr warnings into errors
    if ($LASTEXITCODE -eq 0) { break }
    if ((Get-Date) -gt $deadline) { Write-Host 'MISP did not come up within 20 min.'; exit 1 }
    Write-Host "attempt ${try}: still starting (healthchecks not passing yet); retrying in 30 s..."
    Start-Sleep -Seconds 30
}

if (-not $NoWait) {
    Write-Host 'Waiting for MISP to answer on https://127.0.0.1:8443 (first start can take 5-10 min)...'
    $deadline = (Get-Date).AddMinutes(15)
    do {
        Start-Sleep -Seconds 10
        $code = & curl.exe -s -k -o NUL -w '%{http_code}' https://127.0.0.1:8443/users/login
    } until ($code -eq '200' -or (Get-Date) -gt $deadline)
    if ($code -ne '200') { Write-Host "MISP not ready yet (HTTP $code). Check: docker logs hexbrief-misp-misp-core-1"; exit 1 }
}
Write-Host 'MISP is up: https://127.0.0.1:8443  (initial admin: ADMIN_EMAIL / ADMIN_PASSWORD in docker\misp\.env.misp)'
